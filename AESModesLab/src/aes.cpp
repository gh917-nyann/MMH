const std::array<AES::Word, 10> AES::RCON = {{
    {0x01,0x00,0x00,0x00}, {0x02,0x00,0x00,0x00},
    {0x04,0x00,0x00,0x00}, {0x08,0x00,0x00,0x00},
    {0x10,0x00,0x00,0x00}, {0x20,0x00,0x00,0x00},
    {0x40,0x00,0x00,0x00}, {0x80,0x00,0x00,0x00},
    {0x1B,0x00,0x00,0x00}, {0x36,0x00,0x00,0x00}
}};

AES::AES(const std::vector<Byte>& key, int keyLengthBits)
    : key_(key) {
    if (keyLengthBits == 0)
        keyLengthBits = static_cast<int>(key.size() * 8);

    if (keyLengthBits != 128 && keyLengthBits != 192 && keyLengthBits != 256)
        throw std::invalid_argument("AES key length must be 128, 192, or 256 bits.");

    const std::size_t expected = static_cast<std::size_t>(keyLengthBits / 8);
    if (key.size() != expected)
        throw std::invalid_argument("Key byte length does not match keyLengthBits.");

    keyLength_ = keyLengthBits;
    numRounds_ = keyLengthBits / 32 + 6;
    roundKeys_ = keyExpansion(key_);
}

AES::Block AES::encrypt(const Block& input, bool trace) const {
    (void)trace; // The original round transformations are unchanged.
    State s = bytesToState(input);
    addRoundKey(s, 0);

    for (int round = 1; round < numRounds_; ++round) {
        subBytes(s);
        shiftRows(s);
        mixColumns(s);
        addRoundKey(s, round);
    }

    subBytes(s);
    shiftRows(s);
    addRoundKey(s, numRounds_);
    return stateToBytes(s);
}

AES::Block AES::decrypt(const Block& input, bool trace) const {
    (void)trace; // The original round transformations are unchanged.
    State s = bytesToState(input);
    addRoundKey(s, numRounds_);

    for (int round = numRounds_ - 1; round > 0; --round) {
        invShiftRows(s);
        invSubBytes(s);
        addRoundKey(s, round);
        invMixColumns(s);
    }

    invShiftRows(s);
    invSubBytes(s);
    addRoundKey(s, 0);
    return stateToBytes(s);
}

void AES::printAllRoundKeys() const {
    for (int round = 0; round <= numRounds_; ++round)
        printRoundKey(round);
}

AES::Byte AES::gmul(Byte a, Byte b) {
    Byte p = 0;
    for (int i = 0; i < 8; ++i) {
        if (b & 1) p ^= a;
        const bool high = (a & 0x80) != 0;
        a = static_cast<Byte>(a << 1);
        if (high) a ^= 0x1B;
        b = static_cast<Byte>(b >> 1);
    }
    return p;
}

AES::State AES::bytesToState(const Block& block) {
    State s{};
    for (int col = 0; col < 4; ++col)
        for (int row = 0; row < 4; ++row)
            s[row][col] = block[4 * col + row];
    return s;
}

AES::Block AES::stateToBytes(const State& s) {
    Block block{};
    for (int col = 0; col < 4; ++col)
        for (int row = 0; row < 4; ++row)
            block[4 * col + row] = s[row][col];
    return block;
}

void AES::subBytes(State& s) {
    for (auto& row : s)
        for (auto& b : row)
            b = S_BOX[b];
}

void AES::invSubBytes(State& s) {
    for (auto& row : s)
        for (auto& b : row)
            b = INV_S_BOX[b];
}

void AES::shiftRows(State& s) {
    for (int row = 1; row < 4; ++row) {
        auto old = s[row];
        for (int col = 0; col < 4; ++col)
            s[row][col] = old[(col + row) % 4];
    }
}

void AES::invShiftRows(State& s) {
    for (int row = 1; row < 4; ++row) {
        auto old = s[row];
        for (int col = 0; col < 4; ++col)
            s[row][col] = old[(col - row + 4) % 4];
    }
}

void AES::mixColumns(State& s) {
    for (int c = 0; c < 4; ++c) {
        Byte a = s[0][c], b = s[1][c], d = s[2][c], e = s[3][c];
        s[0][c] = gmul(0x02, a) ^ gmul(0x03, b) ^ d ^ e;
        s[1][c] = a ^ gmul(0x02, b) ^ gmul(0x03, d) ^ e;
        s[2][c] = a ^ b ^ gmul(0x02, d) ^ gmul(0x03, e);
        s[3][c] = gmul(0x03, a) ^ b ^ d ^ gmul(0x02, e);
    }
}

void AES::invMixColumns(State& s) {
    for (int c = 0; c < 4; ++c) {
        Byte a = s[0][c], b = s[1][c], d = s[2][c], e = s[3][c];
        s[0][c] = gmul(0x0e, a) ^ gmul(0x0b, b) ^ gmul(0x0d, d) ^ gmul(0x09, e);
        s[1][c] = gmul(0x09, a) ^ gmul(0x0e, b) ^ gmul(0x0b, d) ^ gmul(0x0d, e);
        s[2][c] = gmul(0x0d, a) ^ gmul(0x09, b) ^ gmul(0x0e, d) ^ gmul(0x0b, e);
        s[3][c] = gmul(0x0b, a) ^ gmul(0x0d, b) ^ gmul(0x09, d) ^ gmul(0x0e, e);
    }
}

void AES::addRoundKey(State& s, int round) const {
    for (int col = 0; col < 4; ++col)
        for (int row = 0; row < 4; ++row)
            s[row][col] ^= roundKeys_[round * 4 + col][row];
}

AES::Word AES::rotWord(Word w) {
    return {w[1], w[2], w[3], w[0]};
}

AES::Word AES::subWord(Word w) {
    return {S_BOX[w[0]], S_BOX[w[1]], S_BOX[w[2]], S_BOX[w[3]]};
}

std::vector<AES::Word> AES::keyExpansion(const std::vector<Byte>& key) const {
    const int nk = keyLength_ / 32;
    const int totalWords = 4 * (numRounds_ + 1);
    std::vector<Word> words(static_cast<std::size_t>(totalWords));

    for (int i = 0; i < nk; ++i)
        for (int j = 0; j < 4; ++j)
            words[i][j] = key[4 * i + j];

    for (int i = nk; i < totalWords; ++i) {
        Word temp = words[i - 1];
        if (i % nk == 0) {
            temp = subWord(rotWord(temp));
            const int rconIndex = i / nk - 1;
            for (int j = 0; j < 4; ++j)
                temp[j] ^= RCON[rconIndex][j];
        } else if (nk > 6 && i % nk == 4) {
            temp = subWord(temp);
        }

        for (int j = 0; j < 4; ++j)
            words[i][j] = words[i - nk][j] ^ temp[j];
    }

    return words;
}

std::string AES::byteToHex(Byte b) {
    static constexpr char digits[] = "0123456789abcdef";
    std::string result(2, '0');
    result[0] = digits[(b >> 4) & 0x0F];
    result[1] = digits[b & 0x0F];
    return result;
}

void AES::printRoundKey(int round) const {
    std::cout << "Round " << round << " key: ";
    for (int col = 0; col < 4; ++col) {
        for (int row = 0; row < 4; ++row)
            std::cout << byteToHex(roundKeys_[round * 4 + col][row]);
    }
    std::cout << '\n';
}

void AES::printState(const std::string& label, const State& state) {
    std::cout << label << '\n';
    for (const auto& row : state) {
        for (Byte b : row)
            std::cout << byteToHex(b) << ' ';
        std::cout << '\n';
    }
}
